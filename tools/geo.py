#!/usr/bin/env python3
"""Write src/shared/EuropeGeo.luau: real coasts, lakes and rivers for the grand campaign board.

Input: Natural Earth 1:50m GeoJSON (public domain), downloaded into their own directory:
  ne_50m_land.geojson, ne_50m_lakes.geojson, ne_50m_rivers_lake_centerlines.geojson
  from https://github.com/nvkelso/natural-earth-vector/tree/master/geojson
Run: python3 -I tools/geo.py <dir with the three files>

The board uses EuropeData's projection, x = (lon + 10) * 40, z = (lat - 36) * 62.5, on a
2000 x 1500 map. Land is a raster of CELL-unit cells, row by row from z = 0 (south), each row
run-length coded as alternating water/land runs starting with water. Rivers are polylines in map
units, simplified.
"""
import json
import math
import pathlib
import sys

W, D = 2000, 1500
CELL = 8  # map units per raster cell (about 4.4 studs on the board)
COLS, ROWS = W // CELL, D // CELL
RIVER_TOL = 3.0  # Douglas-Peucker tolerance, map units
MIN_RIVER_LEN = 60  # map units: drop stubs

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "shared" / "EuropeGeo.luau"


def proj(lon, lat):
    return (lon + 10) * 40, (lat - 36) * 62.5


def rings(geom):
    t, c = geom["type"], geom["coordinates"]
    if t == "Polygon":
        return [r for r in c]
    if t == "MultiPolygon":
        return [r for poly in c for r in poly]
    return []


def lines(geom):
    t, c = geom["type"], geom["coordinates"]
    if t == "LineString":
        return [c]
    if t == "MultiLineString":
        return c
    return []


def edges_of(features):
    """Projected ring edges crossing the map's rows, for even-odd scanline fills."""
    out = []
    for f in features:
        for ring in rings(f["geometry"]):
            pts = [proj(lon, lat) for lon, lat in ring]
            for (x1, z1), (x2, z2) in zip(pts, pts[1:]):
                # only rows matter: edges off the map's sides still count for the even-odd fill
                if max(z1, z2) < 0 or min(z1, z2) > D:
                    continue
                if z1 != z2:
                    out.append((x1, z1, x2, z2))
    return out


def fill(edges):
    grid = [[0] * COLS for _ in range(ROWS)]
    for r in range(ROWS):
        zc = (r + 0.5) * CELL
        xs = []
        for x1, z1, x2, z2 in edges:
            if (z1 <= zc < z2) or (z2 <= zc < z1):
                xs.append(x1 + (zc - z1) * (x2 - x1) / (z2 - z1))
        xs.sort()
        for a, b in zip(xs[0::2], xs[1::2]):
            c0 = max(0, math.ceil(a / CELL - 0.5))
            c1 = min(COLS - 1, math.floor(b / CELL - 0.5))
            for c in range(c0, c1 + 1):
                grid[r][c] = 1
    return grid


def rle(row):
    runs, cur, n = [], 0, 0
    for v in row:
        if v == cur:
            n += 1
        else:
            runs.append(n)
            cur, n = v, 1
    runs.append(n)
    return runs


def simplify(pts, tol):
    if len(pts) < 3:
        return pts
    (x1, z1), (x2, z2) = pts[0], pts[-1]
    dx, dz = x2 - x1, z2 - z1
    L = math.hypot(dx, dz) or 1e-9
    far, idx = -1.0, 0
    for i in range(1, len(pts) - 1):
        px, pz = pts[i]
        d = abs(dz * px - dx * pz + x2 * z1 - z2 * x1) / L
        if d > far:
            far, idx = d, i
    if far <= tol:
        return [pts[0], pts[-1]]
    return simplify(pts[: idx + 1], tol)[:-1] + simplify(pts[idx:], tol)


def inside(x, z):
    return 0 <= x <= W and 0 <= z <= D


def main():
    src = pathlib.Path(sys.argv[1])
    land = json.loads((src / "ne_50m_land.geojson").read_text())["features"]
    lakes = json.loads((src / "ne_50m_lakes.geojson").read_text())["features"]
    rivers = json.loads((src / "ne_50m_rivers_lake_centerlines.geojson").read_text())["features"]

    grid = fill(edges_of(land))
    wet = fill(edges_of(lakes))
    for r in range(ROWS):
        for c in range(COLS):
            if wet[r][c]:
                grid[r][c] = 0

    out_rivers = []
    for f in rivers:
        p = f["properties"]
        if p.get("featurecla") not in ("River", "Lake Centerline"):
            continue
        if (p.get("scalerank") or 9) > 6:
            continue
        name = p.get("name") or p.get("name_en") or ""
        for line in lines(f["geometry"]):
            pts = [proj(lon, lat) for lon, lat in line]
            run = []
            for q in pts + [None]:
                if q is not None and inside(*q):
                    run.append(q)
                    continue
                if len(run) >= 2:
                    s = simplify(run, RIVER_TOL)
                    length = sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(s, s[1:]))
                    if length >= MIN_RIVER_LEN:
                        out_rivers.append((name, s))
                run = []

    lines_out = [
        "--!strict",
        "-- GENERATED by tools/geo.py from Natural Earth 1:50m (public domain); do not edit by hand.",
        "-- Real coasts, lakes and rivers for the grand campaign board, in EuropeData's map units",
        f"-- ({W} x {D}; x = (lon + 10) * 40, z = (lat - 36) * 62.5). `land` is one string per",
        f"-- {CELL}-unit row from z = 0: comma-separated run lengths, alternating water and land,",
        "-- starting with water. `rivers` are polylines { name, x1, z1, x2, z2, ... }.",
        "",
        "local EuropeGeo = {}",
        f"EuropeGeo.Cell = {CELL}",
        f"EuropeGeo.Cols = {COLS}",
        f"EuropeGeo.Rows = {ROWS}",
        "EuropeGeo.land = {",
    ]
    for r in range(ROWS):
        lines_out.append('\t"' + ",".join(str(n) for n in rle(grid[r])) + '",')
    lines_out.append("}")
    lines_out.append("EuropeGeo.rivers = {")
    for name, pts in out_rivers:
        coords = ", ".join(f"{x:.0f}, {z:.0f}" for x, z in pts)
        lines_out.append(f'\t{{ "{name}", {coords} }},')
    lines_out.append("}")
    lines_out.append("")
    lines_out.append("return EuropeGeo")
    OUT.write_text("\n".join(lines_out) + "\n", encoding="utf-8")
    landc = sum(map(sum, grid))
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB): {landc} land cells of {COLS * ROWS}, {len(out_rivers)} river lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
